df_features = df_features.drop(columns=['dt_inicio', 'dt_fim'])

# 2. Transformações Financeiras
# Diferença de valor (ex: aditivos)
df_features['valor_aditivado'] = df_features['valor_global'] - df_features['valor_inicial']

